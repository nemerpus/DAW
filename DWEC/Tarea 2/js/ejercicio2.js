// Declaramos dos variables de tipo string
let nombre = "Antonio";
let apellido = "Pérez";

// Declaramos dos variables numéricas
let edad = 35;
let nacimiento = 1991;

// Mostramos una frase que contiene comillas simples
alert("Mi nombre es 'Antonio'");

// Mostramos nombre y apellido separados por un salto de línea
alert(nombre + "\n" + apellido);

// Sumamos las dos variables numéricas
alert(edad + nacimiento);

// Sumamos todas las variables
alert(nombre + apellido + edad + nacimiento);